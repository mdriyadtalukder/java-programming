public class _1_Loops {
    public static void main(String[] args) {

        // For loop
        for (int i = 0; i < 10; i++) {
            System.out.println(i);
        }

        // while loop
        int j = 10;
        while (j <= 20) {
            System.out.println(j);
            j++;
        }

        // do while loop
        int k = 30;

        do {
            System.out.println(k);
            k++;
        } while (k <= 40);
    }
}